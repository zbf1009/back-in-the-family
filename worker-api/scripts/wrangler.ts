import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { root, sourceConfig } from './profile.ts';
import { assertWorkerTools } from './tools.ts';
import { checkedWorkerBundle, digest, sourceDigests } from './bundle.ts';

async function main(): Promise<void> {
  const command = process.argv[2];
  assert.ok(['build', 'types:generate', 'types:check'].includes(command ?? ''), 'Expected build, types:generate or types:check');
  assertWorkerTools();
  const output = join(root, 'target/decision-worker');
  if (command === 'build') await rm(output, { recursive: true, force: true });
  const config = await sourceConfig();
  // This is the validated SOURCE profile, with only filesystem paths made absolute.
  // No AI stripping, date/flag override, credentials, custom build or remote binding.
  config.$schema = resolve(root, 'worker-api', config.$schema);
  config.main = resolve(root, 'worker-api', config.main);
  config.assets.directory = resolve(root, 'worker-api', config.assets.directory);
  if (command === 'build') assert.ok((await readFile(join(config.assets.directory, 'index.html'))).byteLength > 0, 'Run the checked Web_Build before Worker_Build');
  const temp = await mkdtemp(join(tmpdir(), 'worker-api-command-'));
  const generated = join(root, 'worker-api/worker-configuration.check.d.ts');
  try {
    await writeFile(join(temp, 'wrangler.jsonc'), JSON.stringify(config));
    const args = command === 'build'
      ? ['deploy', '--dry-run', '--outdir', './bundle', '--config', './wrangler.jsonc']
      : ['types', command === 'types:generate' ? join(root, 'worker-api/worker-configuration.d.ts') : generated,
        '--config', './wrangler.jsonc', '--env-interface', 'WranglerEnv'];
    const result = spawnSync(process.execPath, [join(root, 'web/node_modules/wrangler/bin/wrangler.js'), ...args], {
      cwd: temp, stdio: 'inherit',
    });
    if (result.error) throw result.error;
    assert.equal(result.status, 0, `Pinned Wrangler ${command} failed`);
    if (command === 'types:check') {
      // Compare the actual regenerated body and runtime header, not just Wrangler's
      // input hash (--check ignores edits to the declaration body). The invocation
      // comment alone differs because the disposable output filename differs.
      const [regenerated, current] = await Promise.all([generated, join(root, 'worker-api/worker-configuration.d.ts')].map(async path =>
        (await readFile(path, 'utf8')).split('\n').filter(line => !line.startsWith('// Generated by Wrangler by running ')).join('\n')));
      assert.equal(regenerated, current,
        'Generated Worker declarations differ; run types:generate with the pinned source profile');
    }
    if (command === 'build') {
      const files = await readdir(join(temp, 'bundle'));
      assert.deepEqual(files.filter(path => path.endsWith('.js')), ['index.js'], 'Expected one bundled Worker module');
      const bytes = await readFile(join(temp, 'bundle/index.js'));
      assert.ok(bytes.byteLength > 0 && bytes.byteLength <= 26_214_400, 'Worker module exceeds the existing file limit');
      await mkdir(output, { recursive: true });
      await writeFile(join(output, 'worker.js'), bytes);
      await writeFile(join(output, 'build.json'), JSON.stringify({ version: 1, bundle: digest(bytes), sources: await sourceDigests() }) + '\n');
      await checkedWorkerBundle();
      console.log('Worker_Build staged the exact checked bundle: target/decision-worker/worker.js');
    }
  } finally {
    if (command === 'types:check') await rm(generated, { force: true });
    await rm(temp, { recursive: true, force: true });
  }
}
await main();
