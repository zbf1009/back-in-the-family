import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { root, sourceConfig, validateJudgeHostedConfig, workerProfile } from './profile.ts';
import type { WorkerProfile } from './profile.ts';
import { assertWorkerTools } from './tools.ts';
import { checkedWorkerBundle, digest, sourceDigests } from './bundle.ts';

const runtimeMarker = '// Begin runtime types';
function splitTypes(text: string): { header: string; runtime: string } {
  const lines = text.split('\n');
  const markers = lines.flatMap((line, index) => line === runtimeMarker ? [index] : []);
  assert.equal(markers.length, 1, 'Pinned Wrangler declarations must have exactly one runtime marker');
  const index = markers[0]!;
  return { header: lines.slice(0, index).join('\n') + '\n', runtime: lines.slice(index).join('\n') };
}

async function main(): Promise<void> {
  const command = process.argv[2];
  assert.ok(['build', 'types:generate', 'types:check'].includes(command ?? ''), 'Expected build, types:generate or types:check');
  const profile = workerProfile(process.argv.slice(3));
  const headerPath = join(root, profile === 'judge' ? 'worker-api/judge-configuration.d.ts' : 'worker-api/worker-configuration.d.ts');
  assertWorkerTools();
  const output = join(root, profile === 'judge' ? 'target/judge-worker' : 'target/decision-worker');
  const temp = await mkdtemp(join(tmpdir(), 'worker-api-command-'));
  try {
    const selected = await sourceConfig(profile);
    const run = async (selectedProfile: WorkerProfile, build: boolean): Promise<string> => {
      const config = await sourceConfig(selectedProfile);
      // Only filesystem paths change in the validated source profile.
      config.$schema = resolve(root, 'worker-api', config.$schema);
      config.main = resolve(root, 'worker-api', config.main);
      config.assets.directory = resolve(root, 'worker-api', config.assets.directory);
      if (build) assert.ok((await readFile(join(config.assets.directory, 'index.html'))).byteLength > 0, 'Run the checked Web_Build before Worker_Build');
      await writeFile(join(temp, 'wrangler.jsonc'), JSON.stringify(config));
      const generated = join(root, `worker-api/${selectedProfile}-configuration.check.d.ts`);
      const args = build
        ? ['deploy', '--dry-run', '--outdir', './bundle', '--config', './wrangler.jsonc']
        : ['types', generated, '--config', './wrangler.jsonc', '--env-interface', selectedProfile === 'judge' ? 'JudgeBindings' : 'WranglerEnv'];
      const result = spawnSync(process.execPath, [join(root, 'web/node_modules/wrangler/bin/wrangler.js'), ...args], { cwd: temp, stdio: 'inherit' });
      if (result.error) throw result.error;
      assert.equal(result.status, 0, `Pinned Wrangler ${command} failed`);
      return build ? '' : await readFile(generated, 'utf8');
    };
    if (command !== 'build') {
      const regenerated = splitTypes(await run(profile, false));
      if (profile === 'judge') {
        const generic = splitTypes(await run('generic', false));
        assert.equal(regenerated.runtime, generic.runtime, 'Judge and generic pinned runtime declarations differ');
      }
      const sharedPath = join(root, 'worker-api/runtime-configuration.d.ts');
      if (command === 'types:generate') {
        await writeFile(headerPath, regenerated.header);
        await writeFile(sharedPath, regenerated.runtime);
      } else {
        const currentHeader = await readFile(headerPath, 'utf8');
        assert.ok(!currentHeader.split('\n').includes(runtimeMarker), 'Binding declarations must not duplicate runtime types');
        const [actual, expected] = [regenerated.header, currentHeader].map(text =>
          text.split('\n').filter(line => !line.startsWith('// Generated by Wrangler by running ')).join('\n'));
        assert.equal(actual, expected, 'Generated binding declarations differ; run pinned types:generate');
        assert.equal(regenerated.runtime, await readFile(sharedPath, 'utf8'), 'Generated shared runtime declarations differ; run pinned types:generate');
      }
      return;
    }
    let disabled: unknown;
    if (profile === 'judge') {
      const hosted: unknown = JSON.parse(await readFile(join(root, 'worker-api/judge-hosted.jsonc'), 'utf8'));
      validateJudgeHostedConfig(hosted);
      disabled = { ...selected, $schema: '../../web/node_modules/wrangler/config-schema.json', main: './worker.js', no_bundle: true,
        assets: { ...selected.assets, directory: '../../web/dist' }, vars: { ...selected.vars, INFERENCE_ENABLED: 'false' } };
      validateJudgeHostedConfig(disabled, 'disabled');
    }
    await run(profile, true);
    const files = await readdir(join(temp, 'bundle'));
    const moduleName = profile === 'judge' ? 'judge.js' : 'index.js';
    assert.deepEqual(files.filter(path => path.endsWith('.js')), [moduleName], 'Expected one bundled Worker module');
    const bytes = await readFile(join(temp, 'bundle', moduleName));
    assert.ok(bytes.byteLength > 0 && bytes.byteLength <= 26_214_400, 'Worker module exceeds the existing file limit');
    await rm(output, { recursive: true, force: true });
    await mkdir(output, { recursive: true });
    await writeFile(join(output, 'worker.js'), bytes);
    await writeFile(join(output, 'build.json'), JSON.stringify({ version: 1, bundle: digest(bytes), sources: await sourceDigests(root, profile) }) + '\n');
    if (disabled) await writeFile(join(output, 'deploy-disabled.jsonc'), JSON.stringify(disabled, null, 2) + '\n');
    await checkedWorkerBundle(root, profile);
    console.log(`Worker_Build staged the exact checked ${profile} bundle: ${profile === 'judge' ? 'target/judge-worker' : 'target/decision-worker'}/worker.js`);
  } finally {
    await Promise.all(['generic', 'judge'].map(profile => rm(join(root, `worker-api/${profile}-configuration.check.d.ts`), { force: true })));
    await rm(temp, { recursive: true, force: true });
  }
}
await main();
