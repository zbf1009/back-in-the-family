/** Omit unsupported complete lines rather than filling them with invented facts. */
export function supportedText(template: string, values: Readonly<Record<string, string | undefined>>): string | null {
  let supported = true;
  const line = template.replace(/\{([^}]+)\}/g, (_, key: string) => {
    const value = values[key];
    if (value === undefined) { supported = false; return ''; }
    return value;
  });
  return supported ? line : null;
}
